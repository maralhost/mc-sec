$maral = Db::table('mod_mcsec_assets')->where('client_id', 1)->where('value', '198.51.100.7')->first();
ok($maral && $maral->status === 'verified' && $maral->method === 'whmcs', 'a Maral server IP of the same account is verified at once');
setting('allow_private_ips', '0');
Assets::remove($who, (int) $maral->id);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0, 'removing the IP asset unlinks it');
setting('cdn_origin_scan', '0');
$h = html($page());
ok(!str_contains($h, 'name="origin"') && str_contains($h, 'بررسی سلامت پایه'), 'feature off: no origin form');
