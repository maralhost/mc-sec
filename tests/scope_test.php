section('blocklist forms');
$list = "example.gov   # a domain and its subdomains\n*.mil.ir\n*bank*\nshop*.example.org\n5.6.7.8\n10.20.0.0/16\n5.6.7.100-5.6.7.120\n2001:db8:dead::/48\n# a comment line\n۹.۹.۹.۹";
ok(Net::blocked('domain', 'example.gov', $list) === 'example.gov' && Net::blocked('domain', 'a.b.example.gov', $list) === 'example.gov', 'domain: itself and its subdomains');
ok(Net::blocked('domain', 'notexample.gov', $list) === '', 'domain rule does not match a longer name');
ok(Net::blocked('domain', 'army.mil.ir', $list) === '*.mil.ir' && Net::blocked('domain', 'mil.ir', $list) === '*.mil.ir', '*.zone: subdomains and the zone');
ok(Net::blocked('domain', 'mybank-online.com', $list) === '*bank*' && Net::blocked('domain', 'shop.bankmellat.ir', $list) === '*bank*', 'keyword pattern');
ok(Net::blocked('domain', 'shop2.example.org', $list) === 'shop*.example.org' && Net::blocked('domain', 'www.example.org', $list) === '', 'pattern inside a name');
ok(Net::blocked('ip', '5.6.7.8', $list) === '5.6.7.8' && Net::blocked('ip', '5.6.7.9', $list) === '', 'single IP');
ok(Net::blocked('ip', '10.20.30.40', $list) === '10.20.0.0/16', 'CIDR');
ok(Net::blocked('ip', '5.6.7.110', $list) === '5.6.7.100-5.6.7.120' && Net::blocked('ip', '5.6.7.121', $list) === '', 'range a-b');
ok(Net::blocked('ip', '2001:db8:dead:1::5', $list) === '2001:db8:dead::/48' && Net::blocked('ip', '2001:db8:beef::5', $list) === '', 'IPv6 CIDR');
ok(Net::blocked('cidr', '5.6.7.96/27', $list) === '5.6.7.8' || Net::blocked('cidr', '5.6.7.96/27', $list) === '5.6.7.100-5.6.7.120', 'an asset range that overlaps a rule');
ok(Net::blocked('ip', '9.9.9.9', $list) === '9.9.9.9', 'Persian digits in a rule');
ok(Net::blocked('domain', 'innocent.example', $list, ['93.184.216.1', '10.20.1.1']) === '10.20.0.0/16 (10.20.1.1)', 'a domain pointing at a forbidden IP is forbidden');
ok(Net::blocked('domain', 'innocent.example', $list, ['93.184.216.1']) === '', 'its other IPs are fine');
ok(Net::blocked('domain', 'portal.mof.gov.ir') === '*.gov.ir', 'default list still blocks gov.ir');
ok(Net::inCidr('2606:4700::6810:1', '2606:4700::/32') && Net::inCidr('203.0.113.7', '203.0.113.0/28') && !Net::inCidr('203.0.113.17', '203.0.113.0/28'), 'inCidr v4 and v6');
ok(Net::ipRange('1.2.3.4/33') === null && Net::ipRange('nonsense') === null && Net::ipRange('1.2.3.4-::1') === null, 'bad ranges rejected');

section('CDN detection');
ok(Net::cdnOf('ip', '104.16.1.1') === 'cloudflare' && Net::cdnOf('ip', '2606:4700::1') === 'cloudflare', 'Cloudflare IPv4 and IPv6 from the default list');
ok(Net::cdnOf('ip', '185.143.233.10') === 'arvancloud' && Net::cdnOf('ip', '185.226.142.142') === 'mizbancloud', 'ArvanCloud and MizbanCloud');
ok(Net::cdnOf('ip', '93.184.216.34') === '', 'an ordinary server IP');
dns_a('cf-site.example', '104.16.5.5');
ok(Net::cdnOf('domain', 'cf-site.example') === 'cloudflare', 'domain whose A record is a CDN edge');
$GLOBALS['__dns']['img.example']['CNAME'][] = ['target' => 'd111.cloudfront.net'];
dns_a('img.example', '52.84.1.1');
ok(Net::cdnOf('domain', 'img.example') === 'cloudfront', 'domain whose CNAME is a CDN name');
dns_a('plain.example', '93.184.216.34');
ok(Net::cdnOf('domain', 'plain.example') === '', 'domain on its own server');
ok(Net::cdnOf('cidr', '104.16.0.0/24') === 'cloudflare', 'an asset range inside a CDN');
$saved = Settings::get('cdn_list');
setting('cdn_list', "myedge 198.51.100.0/24   # our own edge");
ok(Net::cdnOf('ip', '198.51.100.9') === 'myedge' && Net::cdnOf('ip', '104.16.1.1') === '', 'the admin list replaces the defaults');
setting('cdn_list', $saved);

section('adding assets');
$r = Assets::add($who, '104.16.9.9');
ok(!$r['ok'] && str_contains($r['error'], 'CDN') && str_contains($r['error'], 'Cloudflare'), 'a CDN IP is never an asset');
ok(!Assets::add($who, '104.16.0.0/28')['ok'], 'nor a CDN range');
$r = Assets::add($who, 'cf-site.example');
ok($r['ok'], 'a domain behind a CDN can be added');
$cf = Db::table('mod_mcsec_assets')->where('id', $r['id'])->first();
ok($cf->cdn === 'cloudflare' && (int) $cf->cdn_checked_at > 0, 'its CDN is noted at once');
setting('blocklist', Settings::get('blocklist') . "\n45.45.45.0/24");
dns_a('pointer.example', '45.45.45.45');
$r = Assets::add($who, 'pointer.example');
ok(!$r['ok'] && str_contains($r['error'], '45.45.45.0/24'), 'a domain pointing at a forbidden range is refused');
$b = Assets::bulk($who, "bulk-cf.example\nplain.example");
dns_a('bulk-cf.example', '104.16.7.7');
$bulkCf = Db::table('mod_mcsec_assets')->where('value', 'bulk-cf.example')->first();
ok(count($b['added']) === 2 && $bulkCf->cdn === '' && (int) $bulkCf->cdn_checked_at === 0, 'bulk add does no DNS');
ok(Assets::detectCdn(microtime(true) + 5) >= 2 && Db::table('mod_mcsec_assets')->where('id', $bulkCf->id)->value('cdn') === 'cloudflare', 'the worker notes the CDN later');

section('scans of a domain behind a CDN');
Verify::adminApprove((int) $cf->id, 'test');
$cf = Db::table('mod_mcsec_assets')->where('id', $cf->id)->first();
Credits::credit(1, 100, 'paid', 'grant', 'grant:scope', 'test');
$bal = Credits::balance(1)['total'];
$q = Scans::queue(1, $cf, 'hygiene', 0, 1);
ok($q['ok'] && (int) Db::table('mod_mcsec_scans')->where('id', $q['scan_id'])->value('asset_id') === (int) $cf->id, 'basic health check runs on the domain (what visitors see)');
setting('cdn_origin_scan', '0');
$q = Scans::queue(1, $cf, 'surface', 0, 1);
ok(!$q['ok'] && str_contains($q['error'], 'CDN') && str_contains($q['error'], 'بررسی سلامت پایه'), 'origin scanning off: surface refused, health check suggested');
ok(Credits::balance(1)['total'] === $bal, 'nothing charged');
ok(!Scans::queue(1, $cf, 'vuln', 0, 1)['ok'], 'vulnerability scan refused too');
setting('cdn_origin_scan', '1');
$q = Scans::queue(1, $cf, 'surface', 0, 1);
ok(!$q['ok'] && str_contains($q['error'], 'IP اصلی'), 'origin scanning on, no origin yet: asks for it');
setting('profiles', json_encode(['recon' => ['enabled' => true]])); // Osmedeus profiles are off by default since 0.3.0
$q = Scans::queue(1, $cf, 'recon', 0, 1, ['admin' => 1]);
ok(!$q['ok'] && str_contains($q['error'], 'فقط برای دامنه'), 'a domain-only profile cannot move to the origin');

section('the origin server (customer action)');
$page = fn () => client_get(['p' => 'asset', 'id' => (string) $cf->id]);
$h = html($page());
ok(str_contains($h, 'این دامنه پشت CDN است') && str_contains($h, 'name="origin"') && str_contains($h, 'value="asset_origin"'), 'asset page: CDN card with the origin form');
$post = fn (array $p, bool $nonce = true) => client_post('asset_origin', $p + ['asset' => (string) $cf->id], ['p' => 'asset', 'id' => (string) $cf->id], $nonce);
$r = $post(['origin' => '104.16.3.3']);
ok(str_contains(flash_of($r), 'CDN') && (int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0, 'a CDN IP is not an origin');
$r = $post(['origin' => '<script>alert(9)</script>']);
ok(!str_contains(html($r), '<script>alert(9)</script>') && str_contains(flash_of($r), 'IP اصلی'), 'XSS attempt: refused, not echoed');
$r = $post(['origin' => 'cf-site.example']);
ok(str_contains(flash_of($r), 'یک IP'), 'a domain is not an origin');
$r = $post(['origin' => '93.184.216.50'], false);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0, 'without the one-time nonce: nothing changes');
$_POST = [];
login(2, 2);
$r = client_post('asset_origin', ['asset' => (string) $cf->id, 'origin' => '93.184.216.50'], ['p' => 'asset', 'id' => (string) $cf->id]);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0 && !Db::table('mod_mcsec_assets')->where('client_id', 2)->where('value', '93.184.216.50')->exists(), 'another account cannot set it (IDOR)');
login(11, 1);
client_post('asset_origin', ['asset' => (string) $cf->id, 'origin' => '93.184.216.50'], ['p' => 'asset', 'id' => (string) $cf->id]);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0, 'a viewer cannot set it');
$who = login(1, 1);
$r = $post(['origin' => '93.184.216.50']);
$origin = Db::table('mod_mcsec_assets')->where('client_id', 1)->where('value', '93.184.216.50')->first();
ok($origin && $origin->kind === 'ip' && $origin->status === 'pending' && (int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === (int) $origin->id, 'origin linked as a new IP asset, pending its own proof');
ok(str_contains(flash_of($r), 'تأیید کنید'), 'the customer is told to verify it');
$cf = Db::table('mod_mcsec_assets')->where('id', $cf->id)->first();
$q = Scans::queue(1, $cf, 'surface', 0, 1);
ok(!$q['ok'] && str_contains($q['error'], 'هنوز تأیید نشده'), 'an unverified origin is never scanned');
Verify::adminApprove((int) $origin->id, 'test');
$bal = Credits::balance(1)['total'];
$q = Scans::queue(1, $cf, 'surface', 0, 1);
$scan = $q['ok'] ? Db::table('mod_mcsec_scans')->where('id', $q['scan_id'])->first() : null;
ok($q['ok'] && $q['via'] === '93.184.216.50' && (int) $scan->asset_id === (int) $origin->id, 'verified origin: the scan runs on it');
ok(Credits::balance(1)['total'] === $bal - (int) $q['credits'] && (int) $q['credits'] > 0, 'charged once, like any scan');
$h = html(client_get(['p' => 'scan', 'id' => (string) $scan->id]));
ok(str_contains($h, 'سرور اصلی') && str_contains($h, 'cf-site.example'), 'the scan page says which domain it is for');
$h = html($page());
ok(str_contains($h, '93.184.216.50') && str_contains($h, 'برداشتن پیوند') && !str_contains($h, 'name="origin" maxlength'), 'asset page shows the origin and the unlink button');
$h = html(client_get(['p' => 'asset', 'id' => (string) $origin->id]));
ok(str_contains($h, 'سرور اصلی برای') && str_contains($h, 'cf-site.example'), 'the IP page links back to its domain');
$h = html(client_get(['p' => 'assets']));
ok(str_contains($h, 'پشت CDN'), 'asset list marks CDN domains');
$r = $post(['origin' => '']);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === 0 && Db::table('mod_mcsec_assets')->where('id', $origin->id)->value('status') === 'verified', 'unlink keeps the IP asset');
$post(['origin' => '93.184.216.50']);
ok((int) Db::table('mod_mcsec_assets')->where('id', $cf->id)->value('origin_id') === (int) $origin->id, 'an existing IP asset is linked again, not duplicated');
setting('allow_private_ips', '1');
