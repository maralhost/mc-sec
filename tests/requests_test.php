<?php
// 0.15.0 paid work by a person: «بررسی و رفع عیب» (a fixed number of credits, taken when sent, back when the team
// cancels) and «تست دستی» (the team writes a price; the customer accepts: credits when the wallet has them, otherwise
// a WHMCS invoice; work after payment). Every request is a row for the admin panel and a ticket. Idempotency, no
// negative balance, the price never from the browser, IDOR, CSRF/nonce, tiers, XSS, tbl* only through localAPI.
declare(strict_types=1);
require __DIR__ . '/bootstrap.php';

use McSec\Accounts;
use McSec\Admin\Controller as Admin;
use McSec\Clock;
use McSec\Credits;
use McSec\Db;
use McSec\Requests;
use WHMCS\Database\Capsule;

Clock::$fixed = strtotime('2026-11-25T10:00:00Z');
foreach (['enabled' => '1', 'access_mode' => 'all', 'welcome_credits' => '0'] as $k => $v) {
    setting($k, $v);
}
$who = login(1, 1);
Accounts::ensure(1);
Accounts::ensure(2);
$a1 = Db::table('mod_mcsec_assets')->insertGetId(['client_id' => 1, 'kind' => 'domain', 'value' => 'shop.example', 'status' => 'verified', 'method' => 'admin', 'verified_at' => Clock::now(), 'created_at' => Clock::now()]);
$bal = fn (int $c = 1) => Credits::balance($c)['total'];
$tickets = fn () => as_whmcs(fn () => Capsule::table('tbltickets')->orderBy('id')->get()->all());
$req = fn (int $id) => Db::table('mod_mcsec_requests')->where('id', $id)->first();
$last = fn () => (int) Db::table('mod_mcsec_requests')->max('id');
$spent = fn (int $id) => (int) Db::table('mod_mcsec_ledger')->whereIn('ref', ['req:' . $id . ':m', 'req:' . $id . ':p'])->sum('delta');
$send = fn (array $p) => client_post('support_send', $p + ['topic' => 'review', 'asset' => $a1, 'text' => 'لطفاً این را بررسی و درست کنید، ممنون.'], ['p' => 'support']);
$apost = function (string $act, array $post, bool $csrf = true): string {
    $_SERVER['REQUEST_METHOD'] = 'POST';
    $_GET = ['module' => 'mcsec', 'mcsa' => 'requests'];
    $_POST = $post + ['mcsa_act' => $act, 'mcsa_csrf' => $csrf ? \McSec\Auth::csrf() : 'bad'];
    return Admin::handle('addonmodules.php?module=mcsec');
};
$apage = function (array $q = []): string {
    $_SERVER['REQUEST_METHOD'] = 'GET';
    $_GET = ['module' => 'mcsec', 'mcsa' => 'requests'] + $q;
    $_POST = [];
    return Admin::handle('addonmodules.php?module=mcsec');
};
$fresh = fn () => Db::table('mod_mcsec_hits')->where('k', 'like', 'support:%')->delete();

section('off by default');
ok(Requests::kinds() === ['help'], 'only the free question until the admin switches the paid kinds on');
$h = html(client_get(['p' => 'support']));
ok(!str_contains($h, 'name="kind" value="fix"') && !str_contains($h, 'name="kind" value="manual"') && str_contains($h, 'name="kind" value="help"'), 'the form offers no paid kind');
$r = $send(['kind' => 'fix']);
ok(str_contains(flash_of($r), 'در دسترس نیست') && !$tickets() && $last() === 0, 'a paid kind sent anyway is refused: no row, no ticket');
$r = $send(['kind' => 'help']);
$helpId = $last();
ok($helpId > 0 && $req($helpId)->kind === 'help' && (int) $req($helpId)->credits === 0 && $req($helpId)->ticket_tid !== '' && count($tickets()) === 1, 'a free question: a row, a ticket, no credits');

section('review and fix: credits when it is sent');
setting('expert_fix', '1');
setting('expert_fix_cost', '20');
$h = html(client_get(['p' => 'support']));
ok(str_contains($h, 'name="kind" value="fix"') && str_contains($h, '۲۰ اعتبار') && str_contains($h, 'هنگام ثبت کم می‌شود'), 'the form says the cost and when it is taken');
$n = count($tickets());
$r = $send(['kind' => 'fix']);
ok(str_contains(flash_of($r), '۲۰ اعتبار لازم است') && count($tickets()) === $n && $bal() === 0, 'no credits: refused before anything is made');
Credits::credit(1, 50, 'paid', 'topup', 'topup:r1', 'test');
$nonce = \McSec\Nonce::issue(1, 1, 'form');
$r = $send(['kind' => 'fix', 'mcs_nonce' => $nonce]);
$fix = $last();
ok(str_contains((string) ($r['redirect'] ?? ''), 'sent=' . $fix) && $bal() === 30 && $spent($fix) === -20 && $req($fix)->paid_with === 'credits' && $req($fix)->status === 'new', '20 credits taken once, ledger ref req:<id>');
$t = $tickets();
ok(str_starts_with(end($t)->title, '[امنیت سایبری] بررسی و رفع عیب توسط کارشناس: shop.example') && str_contains(end($t)->message, 'درخواست #' . $fix) && str_contains(end($t)->message, '۲۰ اعتبار هنگام ثبت کم شد'), 'the ticket says the kind, the request number and what was charged');
$send(['kind' => 'fix', 'mcs_nonce' => $nonce]);
ok($bal() === 30 && $last() === $fix, 'the same form sent twice: one request, one charge');
ok(str_contains(html(client_get(['p' => 'support', 'sent' => (string) $fix])), '۲۰ اعتبار کم شد'), 'the confirmation says what was taken');
$GLOBALS['__fail_api']['OpenTicket'] = 'down';
$fresh();
$r = $send(['kind' => 'fix']);
$failed = $last();
ok(str_contains(flash_of($r), 'تیکت ساخته نشد') && str_contains(flash_of($r), 'برگشت') && $bal() === 30 && $req($failed)->status === 'cancelled' && (int) $req($failed)->refunded === 20, 'no ticket: the credits come back and the request is closed');
unset($GLOBALS['__fail_api']['OpenTicket']);
setting('expert_fix_cost', '0');
$fresh();
$send(['kind' => 'fix']);
ok($bal() === 30 && (int) $req($last())->credits === 0, 'a cost of zero takes nothing');
setting('expert_fix_cost', '20');

section('the admin panel');
admin('view');
$h = $apage();
ok(str_contains($h, 'درخواست‌های کارشناس') && str_contains($h, 'راهنمای این صفحه') && str_contains($h, 'بررسی و رفع عیب توسط کارشناس') && str_contains($h, 'supporttickets.php?action=view&amp;id='), 'every admin of the panel sees the requests with their tickets');
ok(!str_contains($h, 'name="mcsa_act" value="request_status"') && str_contains($h, 'فقط اجازه‌ی دیدن'), 'a view-only role gets no buttons');
ok(str_contains($apost('request_status', ['id' => $fix, 'to' => 'cancelled']), 'نقش شما') && $req($fix)->status === 'new', 'and cannot act by posting');
admin('ops');
ok(str_contains($apost('request_status', ['id' => $fix, 'to' => 'working'], false), 'منقضی') && $req($fix)->status === 'new', 'CSRF');
ok(str_contains($apost('request_status', ['id' => $fix, 'to' => 'working']), 'ذخیره شد') && $req($fix)->status === 'working', 'ops starts the work');
ok(Db::table('mod_mcsec_notices')->where('client_id', 1)->where('event', 'request_update')->exists(), 'the customer is told');
$r = $apost('request_status', ['id' => $fix, 'to' => 'cancelled']);
ok(str_contains($r, '۲۰ اعتبار به حساب مشتری برگشت') && $bal() === 50 && (int) $req($fix)->refunded === 20, 'cancel gives the credits back');
$apost('request_status', ['id' => $fix, 'to' => 'cancelled']);
ok($bal() === 50, 'cancelling twice refunds once');
ok(str_contains($apost('request_status', ['id' => $fix, 'to' => 'done']), 'ممکن نیست'), 'a cancelled request cannot be marked done');
$_SERVER['REQUEST_METHOD'] = 'GET';
$_GET = ['module' => 'mcsec', 'mcsa' => 'requests', 'mcsa_act' => 'request_status', 'id' => $helpId, 'to' => 'cancelled'];
Admin::handle('addonmodules.php?module=mcsec');
ok($req($helpId)->status === 'new', 'a GET changes nothing');
ok(Requests::waiting() >= 1, 'new requests are counted on the tab');

section('manual test: the team\'s price, the customer\'s yes');
setting('expert_manual', '1');
login(1, 1);
$fresh();
$b0 = $bal();
$r = $send(['kind' => 'manual', 'text' => 'یک تست دستی کامل برای فروشگاه می‌خواهم <script>alert(9)</script>']);
$man = $last();
ok($req($man)->kind === 'manual' && $bal() === $b0 && (int) $req($man)->credits === 0 && str_contains(html(client_get(['p' => 'support', 'sent' => (string) $man])), 'قیمت را پس از بررسی'), 'nothing is taken when it is sent');
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support']);
ok(str_contains(flash_of($r), 'قیمتی برای تأیید نیست') && $bal() === $b0, 'no price yet: nothing to accept');
admin('ops');
ok(str_contains($apost('request_status', ['id' => $man, 'to' => 'working']), 'ممکن نیست'), 'a manual test cannot start before it is paid');
ok(str_contains($apost('request_quote', ['id' => $man, 'credits' => '0', 'amount' => '100']), 'بیشتر از صفر') && str_contains($apost('request_quote', ['id' => $fix, 'credits' => '5']), 'فقط برای درخواست «تست دستی»'), 'a price needs credits and is only for a manual test');
admin('view');
ok(str_contains($apost('request_quote', ['id' => $man, 'credits' => '40']), 'نقش شما') && $req($man)->status === 'new', 'a view-only role cannot quote');
admin('ops');
$r = $apost('request_quote', ['id' => $man, 'credits' => '40', 'amount' => '2500000', 'note' => 'تست دستی فروشگاه در ۳ روز <img src=x onerror=alert(9)>']);
ok(str_contains($r, 'قیمت اعلام شد') && $req($man)->status === 'quoted' && (int) $req($man)->credits === 40 && (float) $req($man)->amount === 2500000.0, 'the price is stored and the request waits for the customer');
$note = Db::table('mod_mcsec_notices')->where('client_id', 1)->where('event', 'request_update')->orderByDesc('id')->first();
ok($note && str_contains((string) $note->title, 'قیمت تست دستی شما اعلام شد') && $bal() === $b0, 'the customer is told; still nothing taken');
$h = $apage();
ok(!str_contains($h, '<script>alert(9)') && !str_contains($h, '<img src=x') && str_contains($h, '&lt;script&gt;'), 'the customer\'s text and the note are escaped in the panel');
login(1, 1);
$h = html(client_get(['p' => 'support']));
ok(str_contains($h, 'قیمت تست دستی شما آماده است') && str_contains($h, '۴۰ اعتبار') && str_contains($h, 'value="request_accept"') && !str_contains($h, '<img src=x') && str_contains($h, 'تأیید و کسر اعتبار'), 'the price card: the amount, the note escaped, accept with credits');
$r = client_post('request_accept', ['id' => $man], ['p' => 'support']);
ok(str_contains(flash_of($r), 'تیک') && $req($man)->status === 'quoted', 'no tick: no acceptance');
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support'], false);
ok(str_contains(flash_of($r), 'یک بار') && $bal() === $b0, 'no nonce: refused');
$r = client_post('request_accept', ['id' => $man, 'agree' => '1', 'mcs_csrf' => 'bad'], ['p' => 'support']);
ok(str_contains(flash_of($r), 'منقضی') && $bal() === $b0, 'CSRF');
login(12, 1);
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support']);
ok(str_contains(flash_of($r), 'فاکتورها') && $bal() === $b0 && !str_contains(html(client_get(['p' => 'support'])), 'value="request_accept"'), 'a user without the invoices permission cannot accept');
login(1, 1, true);
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support']);
ok($bal() === $b0 && $req($man)->status === 'quoted', 'support behind "login as client" cannot accept for the customer');
login(2, 2);
Credits::credit(2, 500, 'paid', 'topup', 'topup:r2', 'test');
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support']);
ok(str_contains(flash_of($r), 'پیدا نشد') && $bal(2) === 500 && $req($man)->status === 'quoted' && !str_contains(html(client_get(['p' => 'support'])), 'قیمت تست دستی شما آماده است'), 'IDOR: another account neither sees nor accepts it');
login(1, 1);
$r = client_post('request_accept', ['id' => $man, 'agree' => '1', 'credits' => '1', 'amount' => '1'], ['p' => 'support']);
ok(str_contains((string) ($r['redirect'] ?? ''), 'accepted=' . $man) && $bal() === $b0 - 40 && $spent($man) === -40 && $req($man)->status === 'accepted' && $req($man)->paid_with === 'credits', 'accept: exactly the team\'s price is taken, whatever the browser sends');
$r = client_post('request_accept', ['id' => $man, 'agree' => '1'], ['p' => 'support']);
ok($bal() === $b0 - 40 && $spent($man) === -40, 'accepting again takes nothing more');
ok(str_contains(html(client_get(['p' => 'support', 'accepted' => (string) $man])), 'قیمت را پذیرفتید'), 'the customer sees it was accepted');
admin('ops');
ok(str_contains($apost('request_quote', ['id' => $man, 'credits' => '400']), 'فقط برای درخواست') && (int) $req($man)->credits === 40, 'a paid request cannot be re-priced');
ok(str_contains($apost('request_status', ['id' => $man, 'to' => 'working']), 'ذخیره شد') && str_contains($apost('request_status', ['id' => $man, 'to' => 'done']), 'ذخیره شد') && $req($man)->status === 'done' && (int) $req($man)->closed_at > 0, 'paid: the team starts and finishes');

section('manual test without enough credits: an invoice');
login(1, 1);
$fresh();
$send(['kind' => 'manual']);
$m2 = $last();
admin('ops');
$apost('request_quote', ['id' => $m2, 'credits' => '900', 'amount' => '0']);
login(1, 1);
$h = html(client_get(['p' => 'support']));
ok(str_contains($h, 'کافی نیست') && str_contains($h, 'disabled') && str_contains($h, 'خرید اعتبار'), 'short of credits and no invoice amount: the card says to buy credits');
$b1 = $bal();
$r = client_post('request_accept', ['id' => $m2, 'agree' => '1'], ['p' => 'support']);
ok(str_contains(flash_of($r), 'اعتبار کافی نیست') && $bal() === $b1 && $req($m2)->status === 'quoted', 'accepting is refused and nothing is taken');
admin('ops');
$apost('request_quote', ['id' => $m2, 'credits' => '900', 'amount' => '45000000', 'note' => 'تست کامل']);
login(1, 1);
$h = html(client_get(['p' => 'support']));
ok(str_contains($h, 'تأیید و ساخت فاکتور') && str_contains($h, '۴۵٬۰۰۰٬۰۰۰'), 'with an invoice amount the card offers an invoice');
$inv0 = as_whmcs(fn () => Capsule::table('tblinvoices')->count());
$r = client_post('request_accept', ['id' => $m2, 'agree' => '1'], ['p' => 'support']);
$row = $req($m2);
ok(str_contains((string) ($r['redirect'] ?? ''), 'viewinvoice.php?id=' . (int) $row->invoice_id) && $row->status === 'invoiced' && $bal() === $b1 && (float) as_whmcs(fn () => Capsule::table('tblinvoices')->where('id', $row->invoice_id)->value('total')) === 45000000.0, 'an unpaid invoice of the team\'s amount; no credits touched');
$call = array_values(array_filter($GLOBALS['__localapi'], fn ($c) => $c[0] === 'CreateInvoice'));
ok(str_contains((string) end($call)[1]['itemdescription1'], '#R' . $m2) && !isset(end($call)[1]['noemail']), 'the invoice line names the request');
$r = client_post('request_accept', ['id' => $m2, 'agree' => '1'], ['p' => 'support']);
ok(as_whmcs(fn () => Capsule::table('tblinvoices')->count()) === $inv0 + 1 && str_contains((string) ($r['redirect'] ?? ''), 'viewinvoice.php?id=' . (int) $row->invoice_id), 'accepting again goes to the same invoice');
admin('ops');
ok(str_contains($apost('request_status', ['id' => $m2, 'to' => 'working']), 'ممکن نیست'), 'unpaid: the work cannot start');
pay_invoice((int) $row->invoice_id);
ok($req($m2)->status === 'accepted' && $req($m2)->paid_with === 'invoice' && $bal() === $b1, 'paid in WHMCS: the request moves on, the wallet is untouched');
pay_invoice((int) $row->invoice_id);
ok(Db::table('mod_mcsec_notices')->where('client_id', 1)->where('event', 'request_update')->where('title', 'like', '%پرداخت درخواست%')->count() === 1, 'the payment is announced once');
$r = $apost('request_status', ['id' => $m2, 'to' => 'cancelled']);
ok($bal() === $b1 && $req($m2)->status === 'cancelled' && (int) $req($m2)->refunded === 0, 'cancelling an invoiced request refunds no credits (the invoice is handled in WHMCS)');

section('decline, a foreign invoice, a stuck click');
login(1, 1);
$fresh();
$send(['kind' => 'manual']);
$m3 = $last();
admin('ops');
$apost('request_quote', ['id' => $m3, 'credits' => '10', 'amount' => '500000']);
login(2, 2);
ok(str_contains(flash_of(client_post('request_decline', ['id' => $m3], ['p' => 'support'])), 'قیمتی برای رد کردن نیست') && $req($m3)->status === 'quoted', 'IDOR: another account cannot decline it');
login(1, 1);
$b2 = $bal();
$r = client_post('request_decline', ['id' => $m3], ['p' => 'support']);
ok(str_contains(flash_of($r), 'چیزی کم نشد') && $req($m3)->status === 'declined' && $bal() === $b2, 'declined: closed, nothing taken');
ok(str_contains(flash_of(client_post('request_accept', ['id' => $m3, 'agree' => '1'], ['p' => 'support'])), 'قیمتی برای تأیید نیست') && $bal() === $b2, 'a declined price cannot be accepted');
$fresh();
$send(['kind' => 'manual']);
$m4 = $last();
$other = as_whmcs(fn () => Capsule::table('tblinvoices')->insertGetId(['userid' => 2, 'status' => 'Paid', 'total' => 1]));
Db::table('mod_mcsec_requests')->where('id', $m4)->update(['status' => 'invoiced', 'invoice_id' => $other, 'credits' => 10, 'amount' => 1]);
ok(Requests::invoicePaid($other) === 0 && $req($m4)->status === 'invoiced', 'an invoice of another account never pays a request');
Db::table('mod_mcsec_requests')->where('id', $m4)->update(['status' => 'paying', 'invoice_id' => 0, 'updated_at' => Clock::now() - 3600]);
Requests::reconcile();
ok($req($m4)->status === 'quoted', 'a click that died half way: the price is offered again when no credits were taken');
ok($bal() >= 0 && $bal(2) === 500 && (int) Db::table('mod_mcsec_wallets')->min('paid') >= 0 && (int) Db::table('mod_mcsec_wallets')->min('monthly') >= 0, 'no wallet is ever negative');

section('the switch');
setting('support_requests', '0');
ok(Requests::kinds() === [] && str_contains(flash_of($send(['kind' => 'manual'])), 'در دسترس نیست'), 'expert requests off: no kind can be sent');

done();
